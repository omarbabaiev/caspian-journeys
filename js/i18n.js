  let current = 'az';

  function T(text, lang) {
    const key = String(text == null ? '' : text);
    const row = TBL[key];
    if (!row) return key;
    const target = lang || current;
    if (target === 'az') return key;
    return target === 'ru' ? row[1] : row[0];
  }

  const TEXT_ATTRS = ['placeholder', 'aria-label', 'alt', 'title'];
  const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'SVG', 'NOSCRIPT', 'TEMPLATE']);

  function apply(root, lang) {
    const target = lang || current;
    const scope = root || document.body;

    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        let parent = node.parentElement;
        while (parent && parent !== scope) {
          if (SKIP_TAGS.has(parent.tagName) || parent.hasAttribute('data-no-i18n')) return NodeFilter.FILTER_REJECT;
          parent = parent.parentElement;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);

    nodes.forEach((node) => {
      const raw = node.nodeValue;
      const trimmed = raw.trim();
      if (!node._cjSrc) node._cjSrc = trimmed;
      const translated = T(node._cjSrc, target);
      if (translated !== trimmed) {
        const lead = raw.slice(0, raw.indexOf(trimmed));
        const tail = raw.slice(raw.indexOf(trimmed) + trimmed.length);
        node.nodeValue = lead + translated + tail;
      }
    });

    const elements = [scope];
    if (scope.querySelectorAll) elements.push.apply(elements, Array.from(scope.querySelectorAll('*')));
    elements.forEach((el) => {
      if (!el.attributes || (el.hasAttribute && el.hasAttribute('data-no-i18n'))) return;
      if (el.closest && el.closest('[data-no-i18n]')) return;
      if (!el._cjAttrs) el._cjAttrs = {};
      TEXT_ATTRS.forEach((attr) => {
        const value = el.getAttribute(attr);
        if (!value) return;
        if (!el._cjAttrs[attr]) el._cjAttrs[attr] = value.trim();
        const translated = T(el._cjAttrs[attr], target);
        if (translated !== value) el.setAttribute(attr, translated);
      });
    });

    return scope;
  }

  function set(lang) {
    current = ['az', 'en', 'ru'].indexOf(lang) >= 0 ? lang : 'az';
    document.documentElement.lang = current;
    apply(document.body, current);
    window.dispatchEvent(new CustomEvent('cj:langchange', { detail: { lang: current } }));
    return current;
  }

  window.CJI18n = { T, apply, set, get current() { return current; }, table: TBL };
